func TestAddedDeps_CopyleftLicense_Flagged(t *testing.T) {
	head := []byte(`{"lockfileVersion":3,"packages":{"node_modules/gpl-thing":{"version":"2.0.0","license":"(MIT OR GPL-3.0-only)"},
		"node_modules/ok":{"version":"1.0.0","license":"Apache-2.0"}}}`)
	got, err := AddedDeps("package-lock.json", nil, head)
	if err != nil {
		t.Fatal(err)
	}
	if len(got) != 2 || got[0].Name != "gpl-thing" || got[0].Class != "copyleft" || got[1].Class != "permissive" {
		t.Fatalf("got %+v, want gpl-thing copyleft and ok permissive", got)
	}
}

func TestAddedDeps_PnpmLock_ListsDirectAndTransitiveWithVersions(t *testing.T) {
	head := []byte(`lockfileVersion: '9.0'

importers:

  .:
    dependencies:
      react:
        specifier: ^18.2.0
        version: 18.2.0
    devDependencies:
      '@vitejs/plugin-react':
        specifier: ^4.0.0
        version: 4.3.1(vite@5.4.0)

packages:

  '@vitejs/plugin-react@4.3.1':
    resolution: {integrity: sha512-a}

  loose-envify@1.4.0:
    resolution: {integrity: sha512-b}

  react@17.0.2:
    resolution: {integrity: sha512-c}

  react@18.2.0:
    resolution: {integrity: sha512-d}

snapshots:

  react@18.2.0:
    dependencies:
      loose-envify: 1.4.0
`)
	got, err := AddedDeps("web/pnpm-lock.yaml", nil, head)
	if err != nil {
		t.Fatal(err)
	}
	want := []Dep{
		{Ecosystem: "npm", Name: "@vitejs/plugin-react", Version: "4.3.1", Class: "unknown", Direct: true},
		{Ecosystem: "npm", Name: "loose-envify", Version: "1.4.0", Class: "unknown"},
		{Ecosystem: "npm", Name: "react", Version: "17.0.2", Class: "unknown"},
		{Ecosystem: "npm", Name: "react", Version: "18.2.0", Class: "unknown", Direct: true},
	}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("got %+v, want %+v", got, want)
	}
	v6 := []byte("lockfileVersion: '6.0'\n\ndependencies:\n  react:\n    specifier: ^18.2.0\n    version: 18.2.0\n\npackages:\n\n  /react@18.2.0:\n    dependencies:\n      loose-envify: 1.4.0\n    dev: false\n\n  /loose-envify@1.4.0:\n    dev: false\n")
	got, err = AddedDeps("pnpm-lock.yaml", nil, v6)
	if err != nil {
		t.Fatal(err)
	}
	if len(got) != 2 || got[0].Name != "loose-envify" || got[0].Direct || got[1].Version != "18.2.0" || !got[1].Direct {
		t.Fatalf("v6: got %+v, want transitive loose-envify@1.4.0 and direct react@18.2.0", got)
	}
}

