func TestAddedDeps_NpmPackageAdded_ListedWithVersion(t *testing.T) {
	base := []byte(`{"lockfileVersion":3,"packages":{"":{"name":"app"},"node_modules/react":{"version":"19.0.0","license":"MIT"}}}`)
	head := []byte(`{"lockfileVersion":3,"packages":{"":{"name":"app"},"node_modules/react":{"version":"19.1.0","license":"MIT"},
		"node_modules/left-pad":{"version":"1.3.0","license":"WTFPL"},"node_modules/react/node_modules/left-pad":{"version":"1.3.0","license":"WTFPL"}}}`)
	got, err := AddedDeps("web/package-lock.json", base, head)
	if err != nil {
		t.Fatal(err)
	}
	want := []Dep{{Ecosystem: "npm", Name: "left-pad", Version: "1.3.0", License: "WTFPL", Class: "unknown"}}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("got %+v, want %+v", got, want)
	}
}

